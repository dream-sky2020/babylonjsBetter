const { resolveRepoPath } = require('./electronWorkspace.cjs');
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const assert = require('node:assert/strict');
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1366, height: 768, webPreferences: { partition: 'ui-preview-workbench-verification', offscreen: true, backgroundThrottling: false } });
  const report = { passed: false, blockedWrites: [], errors: [] };
  window.webContents.on('console-message', event => { if (event.level === 'error') report.errors.push(event.message); });
  window.webContents.session.webRequest.onBeforeRequest({ urls: ['http://127.0.0.1:1184/*'] }, (details, callback) => { const write = !['GET','HEAD','OPTIONS'].includes(details.method); if (write) report.blockedWrites.push(details.url); callback({ cancel: write }); });
  const page = source => window.webContents.executeJavaScript(source);
  const wait = async source => { for (let i=0; i<120; i++) { if (await page(source)) return; await new Promise(resolve => setTimeout(resolve, 100)); } throw new Error(source); };
  const click = label => page(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()===${JSON.stringify(label)}).click();void 0`);
  try {
    await window.loadURL('http://127.0.0.1:1184/labs/standalone/ui-preview-canvas-lab/index.html?preset=equipment_ui');
    await wait(`Boolean(document.querySelector('.ui-workbench'))`);
    await page(`localStorage.removeItem('ui-preview-canvas-lab:workspace:v1');void 0`);
    await window.loadURL('http://127.0.0.1:1184/labs/standalone/ui-preview-canvas-lab/index.html?preset=equipment_ui');
    await wait(`Boolean(document.querySelector('.dialogue-hierarchy .editor-hierarchy-row'))`);
    report.defaultLayout = await page(`(() => { const tree=document.querySelector('.editor-hierarchy-tree').getBoundingClientRect(); const stage=document.querySelector('.preview-stage').getBoundingClientRect(); return {treeHeight:tree.height,stageWidth:stage.width,overflow:document.documentElement.scrollWidth>innerWidth}; })()`);
    assert.ok(report.defaultLayout.treeHeight > 400, JSON.stringify(report.defaultLayout));
    assert.ok(report.defaultLayout.stageWidth > 600); assert.equal(report.defaultLayout.overflow, false);
    await click('组件库');
    await page(`(() => { const input=document.querySelector('[aria-label="搜索组件"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'资源');input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await wait(`document.querySelectorAll('.ui-component-cards > button').length===1`);
    await click('对象层级');
    await page(`document.querySelector('[data-object-id="heading"]').click();void 0`);
    await wait(`document.querySelector('#ui-inspector-layout > button')?.getAttribute('aria-expanded')==='true'`);
    await page(`document.querySelector('#ui-inspector-layout > button').click();document.querySelector('[aria-label="调整对象面板宽度"]').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));void 0`);
    await wait(`document.querySelector('[aria-label="调整对象面板宽度"]').getAttribute('aria-valuenow')==='296'`);
    assert.equal(await page(`Boolean(document.querySelector('.ui-document-switch .ui-saved'))`), true);
    await click('文档设置');
    await wait(`Boolean(document.querySelector('dialog[open]'))`);
    assert.equal(await page(`Boolean(document.querySelector('dialog[open]').textContent.includes('玩家可视区域与安全区'))`), true);
    await page(`document.querySelector('[aria-label="关闭设置"]').click();void 0`);
    await click('视图设置');
    await wait(`Boolean(document.querySelector('dialog[open]'))`);
    assert.equal(await page(`document.querySelector('dialog[open]').textContent.includes('拖动吸附网格')`), true);
    await page(`Array.from(document.querySelectorAll('dialog[open] label')).find(label=>label.textContent.includes('显示玩家可视区域参考框')).querySelector('input').click();void 0`);
    await wait(`!document.querySelector('[data-ui-reference-frame]')`);
    assert.equal(await page(`Boolean(document.querySelector('.ui-document-switch .ui-saved'))`), true);
    await page(`document.querySelector('[aria-label="关闭设置"]').click();void 0`);
    await window.loadURL('http://127.0.0.1:1184/labs/standalone/ui-preview-canvas-lab/index.html?preset=equipment_ui');
    await wait(`Boolean(document.querySelector('#ui-inspector-layout > button'))`);
    assert.equal(await page(`document.querySelector('#ui-inspector-layout > button').getAttribute('aria-expanded')`), 'false');
    assert.equal(await page(`document.querySelector('[aria-label="调整对象面板宽度"]').getAttribute('aria-valuenow')`), '296');
    assert.equal(await page(`Boolean(document.querySelector('[data-ui-reference-frame]'))`), false);
    await click('视图设置');
    await wait(`Boolean(document.querySelector('dialog[open]'))`);
    await page(`Array.from(document.querySelectorAll('dialog[open] label')).find(label=>label.textContent.includes('显示玩家可视区域参考框')).querySelector('input').click();void 0`);
    await page(`document.querySelector('[aria-label="关闭设置"]').click();void 0`);
    await wait(`Boolean(document.querySelector('[data-ui-reference-frame]'))`);
    await click('属性');
    await wait(`document.querySelector('.ui-workbench').dataset.rightOpen==='false'`);
    await click('属性');
    await click('恢复布局');
    await wait(`document.querySelector('#ui-inspector-layout > button').getAttribute('aria-expanded')==='true'`);
    // Multi-selection gets its own inspector rather than editing the last node silently.
    await page(`document.querySelector('[data-object-id="actor-0"]').dispatchEvent(new MouseEvent('click',{bubbles:true,ctrlKey:true}));void 0`);
    await wait(`Boolean(document.querySelector('.ui-multi-inspector'))`);
    await page(`document.querySelector('[data-object-id="heading"]').click();void 0`);
    await click('组件定义检查 · 0 项');
    await wait(`Boolean(document.querySelector('.ui-workbench-issues'))`);
    await page(`document.querySelector('.ui-workbench-issues header button').click();void 0`);
    assert.equal(await page(`Boolean(document.querySelector('.ui-document-switch .ui-saved'))`), true);
    fs.writeFileSync(resolveRepoPath('node_modules/.cache/ui-preview-workbench-1366.png'), (await window.webContents.capturePage()).toPNG());
    window.setSize(1920, 1080);
    await wait(`innerWidth===1920 && Boolean(document.querySelector('[data-ui-node="heading"]'))`);
    await page(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`);
    report.largeReact = await page(`({nodes:document.querySelectorAll('[data-ui-node]').length, canvases:document.querySelectorAll('canvas').length, width:document.querySelector('.ui-react-editor').getBoundingClientRect().width})`);
    assert.ok(report.largeReact.nodes > 20); assert.equal(report.largeReact.canvases, 0);
    await new Promise(resolve => setTimeout(resolve, 250));
    fs.writeFileSync(resolveRepoPath('node_modules/.cache/ui-preview-workbench-1920.png'), (await window.webContents.capturePage()).toPNG());
    window.setSize(800, 680);
    await click('对象 / 组件'); // Close the previously open left sidebar.
    await click('对象 / 组件'); // Open it as an overlay, closing the right sidebar.
    await wait(`getComputedStyle(document.querySelector('.preview-sidebar')).position==='absolute'`);
    assert.equal(await page(`document.documentElement.scrollWidth>innerWidth`), false);
    await page(`document.querySelector('[aria-label="关闭侧栏"]').click();void 0`);
    await wait(`document.querySelector('.ui-workbench').dataset.leftOpen==='false' && document.querySelector('.ui-workbench').dataset.rightOpen==='false'`);
    await wait(`Boolean(document.querySelector('[data-ui-node="heading"]')) && document.querySelectorAll('canvas').length===0`);
    await page(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`);
    await new Promise(resolve => setTimeout(resolve, 250));
    fs.writeFileSync(resolveRepoPath('node_modules/.cache/ui-preview-workbench-narrow.png'), (await window.webContents.capturePage()).toPNG());
    report.workbench = { componentSearch: true, sections: true, width: true, reload: true, settings: true, multiSelection: true, narrow: true, noDocumentEdits: true };
    assert.deepEqual(report.errors, []); assert.deepEqual(report.blockedWrites, []); report.passed = true;
  } catch (error) { report.error = error.stack; fs.writeFileSync(resolveRepoPath('node_modules/.cache/ui-preview-workbench-failed.png'), (await window.webContents.capturePage()).toPNG()); }
  fs.writeFileSync(resolveRepoPath('node_modules/.cache/ui-preview-workbench-verification.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report)); window.destroy(); app.exit(report.passed ? 0 : 1);
});
