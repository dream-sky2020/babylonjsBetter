const { resolveRepoPath } = require('./electronWorkspace.cjs');
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const key = 'dungeon-map-canvas-lab:workspace:v2';
const result = { passed: false, checks: [], errors: [], writes: [] };
app.commandLine.appendSwitch('use-angle', 'swiftshader');
app.commandLine.appendSwitch('enable-unsafe-swiftshader');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1600, height: 1000, webPreferences: { offscreen: true, backgroundThrottling: false } });
  const page = source => window.webContents.executeJavaScript(source);
  const waitFor = async selector => {
    for (let i = 0; i < 200; i++) { if (await page(`Boolean(document.querySelector(${JSON.stringify(selector)}))`)) return;await pause(100); }
    throw new Error(`Missing control: ${selector}`);
  };
  const drag = async (source, target, edge) => {
    const points = await page(`(() => {
      const from = document.querySelector(${JSON.stringify(source)}).getBoundingClientRect(), to = document.querySelector(${JSON.stringify(target)}).getBoundingClientRect();
      return { x: Math.round(from.left+8), y: Math.round(from.top+14), toX: Math.round(${edge === 'right' ? 'to.right-10' : 'to.left+10'}), toY: Math.round(to.top+to.height/2) };
    })()`);
    window.webContents.sendInputEvent({ type: 'mouseDown', x: points.x, y: points.y, button: 'left', clickCount: 1 });
    for (let step = 1; step <= 8; step++) {
      window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(points.x+(points.toX-points.x)*step/8), y: Math.round(points.y+(points.toY-points.y)*step/8), modifiers: ['leftButtonDown'] });
      await pause(35);
    }
    await pause(80);
    const preview = await page(`Boolean(document.querySelector('.editor-dock-drop.${edge}'))`);
    assert.ok(preview, 'Missing drag placement preview');
    window.webContents.sendInputEvent({ type: 'mouseUp', x: points.toX, y: points.toY, button: 'left', clickCount: 1 });
    await pause(150);
  };
  window.webContents.on('console-message', details => { if (details.level === 'error') result.errors.push(details.message); });
  window.webContents.session.webRequest.onBeforeRequest({ urls: ['http://127.0.0.1:1184/*'] }, (details, callback) => {
    const write = !['GET', 'HEAD', 'OPTIONS'].includes(details.method);if (write) result.writes.push(details.url);callback({ cancel: write });
  });
  try {
    await window.loadURL('http://127.0.0.1:1184/labs/standalone/dungeon-map-canvas-lab/index.html');
    await waitFor('.map-dock-panel[data-panel="entities"] .editor-hierarchy-row');
    await page(`document.querySelector('.map-workbench-panel-buttons button:last-child').click()`);
    await pause(150);
    fs.writeFileSync(resolveRepoPath('node_modules/.cache/dungeon-map-browsers-default.png'), (await window.webContents.capturePage()).toPNG());
    await page(`window.check = (value, message) => { if (!value) throw new Error(message); };
      window.wait = ms => new Promise(resolve => setTimeout(resolve, ms));
      window.panel = id => document.querySelector('.map-dock-panel[data-panel="'+id+'"]');
      window.change = (element, value) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(element, value);element.dispatchEvent(new Event('input', { bubbles:true })); };
      window.toolbar = text => [...document.querySelectorAll('.map-workbench-panel-buttons button')].find(button => button.textContent === text);
      check(document.querySelectorAll('.map-dock-panel:not([hidden])').length === 3, 'Three browsers not visible');
      window.entityRow = panel('entities').querySelector('.editor-hierarchy-row');
      window.entityName = entityRow.querySelector('.editor-hierarchy-label').textContent;
      entityRow.click();`);
    await pause(180);
    await page(`check(document.querySelector('.entity-primary-fields input').value === entityName, 'Entity did not select Inspector');
      check(panel('contents').querySelector('.editor-hierarchy-row.selected .editor-hierarchy-label').textContent === entityName, 'Contents selection did not synchronize');
      change(panel('entities').querySelector('input'), entityName);change(panel('contents').querySelector('input'), '__no_match_for_contents__');`);
    await pause(100);
    await page(`check(!panel('contents').querySelector('.editor-hierarchy-row'), 'Contents search failed');
      check(panel('entities').querySelector('.editor-hierarchy-row'), 'Search leaked between panels');
      panel('entities').querySelector('button[aria-label="隐藏实体"]').click();toolbar('实体').click();`);
    await pause(120);
    await page(`check(panel('entities').querySelector('input').value === entityName, 'Search lost on hide/show');
      change(panel('contents').querySelector('input'), '');change(panel('entities').querySelector('input'), '');
      change(panel('components').querySelector('input'), 'spatial-body');`);
    await pause(100);
    await page(`window.componentRow = [...panel('components').querySelectorAll('.editor-hierarchy-row')].find(row => row.dataset.objectId.startsWith('component:') && row.querySelector('.editor-hierarchy-label').textContent !== entityName);
      check(componentRow, 'Missing global component instance');
      window.componentId = componentRow.querySelector('.map-browser-metadata span:last-child').textContent;
      window.ownerName = componentRow.querySelector('.editor-hierarchy-label').textContent;componentRow.click();`);
    await pause(450);
    await page(`check(document.querySelector('.entity-primary-fields input').value === ownerName, 'Component owner selection failed');
      check(document.querySelector('.map-component-anchor[data-selected="true"]').dataset.componentId === componentId, 'Inspector did not focus the component');
      check(panel('entities').querySelector('.editor-hierarchy-row.selected .editor-hierarchy-label').textContent === ownerName, 'Component/entity cross selection failed');
      check(panel('components').querySelector('.editor-hierarchy-row.selected'), 'Component row not highlighted');
      change(panel('components').querySelector('input'), '空间碰撞形状');`);
    await pause(120);
    await page(`check(panel('components').querySelector('.editor-hierarchy-row[data-object-id^="component:"]'), 'Chinese component search failed');
      change(panel('components').querySelector('input'), '');
      panel('components').querySelector('header button[aria-expanded]').click();`);
    await pause(80);
    await page(`check(panel('components').querySelector('.editor-dock-body').hidden, 'Collapse failed');
      panel('components').querySelector('header button[aria-expanded]').click();toolbar('左右排列').click();`);
    await pause(100);
    await page(`const a=panel('contents').getBoundingClientRect(), b=panel('entities').getBoundingClientRect();check(b.left>a.left, 'Horizontal layout failed');toolbar('上下排列').click();`);
    await pause(100);
    result.checks.push('three browsers, independent search, hide/show preserves search, entity/component cross selection, Chinese search, folding and layout presets');
    await drag('.map-dock-panel[data-panel="components"] > header', '.map-dock-panel[data-panel="contents"]', 'right');
    const saved = await page(`localStorage.getItem(${JSON.stringify(key)})`);
    const geometry = await page(`(() => { const a=panel('contents').getBoundingClientRect(),b=panel('components').getBoundingClientRect();return { ax:a.x, bx:b.x, ay:a.y, by:b.y }; })()`);
    assert.ok(geometry.bx > geometry.ax && Math.abs(geometry.ay-geometry.by) < 2, 'Drag failed to dock on right edge');
    const splitter = await page(`(() => {const e=document.querySelector('.map-dock-splitter.x');e.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));return e.getAttribute('aria-valuenow');})()`);
    await pause(100);
    const afterResize = await page(`document.querySelector('.map-dock-splitter.x').getAttribute('aria-valuenow')`);
    assert.notEqual(afterResize, splitter, 'Keyboard split resize failed');
    result.checks.push('real pointer drag with edge preview and keyboard split resize');
    await page(`panel('entities').querySelector('button[aria-label="隐藏实体"]').click()`);
    await pause(80);
    const persisted = await page(`localStorage.getItem(${JSON.stringify(key)})`);
    await window.reload();await waitFor('.map-dock-panel[data-panel="contents"] .editor-hierarchy-row');
    const restored = await page(`localStorage.getItem(${JSON.stringify(key)})`);
    assert.deepEqual(JSON.parse(restored), JSON.parse(persisted));
    assert.equal(JSON.parse(restored).visible.entities, false);
    assert.ok(JSON.stringify(JSON.parse(saved).tree).includes('"axis":"x"'), 'Expected a docked layout tree');
    result.checks.push('reordered tree, split ratio and hidden panels survive reload');
    fs.writeFileSync(resolveRepoPath('node_modules/.cache/dungeon-map-browsers-desktop.png'), (await window.webContents.capturePage()).toPNG());
    window.setSize(760, 820);
    await page(`for (const label of ['地图内容','实体','组件','属性']) { const button=[...document.querySelectorAll('.map-workbench-panel-buttons button')].find(button=>button.textContent===label);if(button.getAttribute('aria-pressed')==='true')button.click(); }`);
    await pause(150);
    const narrow = await page(`({overflow:document.body.scrollWidth>innerWidth, width:document.querySelector('.dungeon-lab__stage').getBoundingClientRect().width})`);
    assert.ok(!narrow.overflow && narrow.width >= 700, JSON.stringify(narrow));
    result.checks.push('narrow viewport can hide all browsers and recover full map width');
    window.setSize(1600, 1000);
    await window.loadURL('http://127.0.0.1:1184/labs/standalone/scene-environment-lab/index.html');
    await waitFor('.environment-dock-panel[data-panel="objects"]');
    await waitFor('#scene-toolbar .environment-toolbar-workspace');
    await page(`const button=[...document.querySelectorAll('button')].find(button=>button.textContent==='恢复默认布局');button.click();`);
    await pause(150);
    await drag('.environment-dock-panel[data-panel="textures"] > header', '.environment-dock-panel[data-panel="objects"]', 'left');
    const environment = await page(`(() => {const a=document.querySelector('[data-panel="objects"]').getBoundingClientRect(),b=document.querySelector('[data-panel="textures"]').getBoundingClientRect();return { ax:a.x,bx:b.x,ay:a.y,by:b.y };})()`);
    assert.ok(environment.bx < environment.ax && Math.abs(environment.ay-environment.by) < 2, 'Shared dock regressed scene environment');
    result.checks.push('scene environment uses shared dock and still supports real pointer reordering');
    assert.deepEqual(result.errors, []);assert.deepEqual(result.writes, []);result.passed = true;
  } catch (error) { result.error = error.stack ?? String(error); }
  fs.writeFileSync(resolveRepoPath('node_modules/.cache/dungeon-map-browsers-verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));window.destroy();app.exit(result.passed ? 0 : 1);
});
